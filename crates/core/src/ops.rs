/// What a quick capture is (M9). Ideas, bugs and TODOs go to the TODO file's Inbox; notes to the app's notes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CaptureKind {
    Idea,
    Bug,
    Todo,
    Note,
}

impl CaptureKind {
    pub const ALL: [CaptureKind; 4] = [CaptureKind::Idea, CaptureKind::Bug, CaptureKind::Todo, CaptureKind::Note];

    pub fn label(self) -> &'static str {
        match self {
            CaptureKind::Idea => "Idea",
            CaptureKind::Bug => "Bug",
            CaptureKind::Todo => "TODO",
            CaptureKind::Note => "Note",
        }
    }

    /// A label, case-insensitive.
    pub fn parse(s: &str) -> Option<CaptureKind> {
        CaptureKind::ALL.into_iter().find(|k| k.label().eq_ignore_ascii_case(s.trim()))
    }
}

/// The TODO file section captures land in.
pub const INBOX: &str = "Inbox";

/// Where a capture went.
pub enum Captured {
    Todo { file: PathBuf, id: String },
    Note(Note),
}

/// File a quick capture. An idea, bug or TODO becomes an item of `## Inbox` in the project's TODO file, in the file's
/// style, prefixed with its kind (`Idea: …`; a TODO has no prefix), details as continuation lines. The Inbox is
/// created above the first section, and `TODO.md` when the project has no TODO file. A note becomes a project note.
pub fn capture(store: &Store, project: &Project, kind: CaptureKind, title: &str, details: &str) -> Result<Captured> {
    let (title, details) = (title.trim(), details.trim());
    if title.is_empty() {
        return fail("a capture needs a title");
    }
    if kind == CaptureKind::Note {
        return Ok(Captured::Note(write_note(store, None, Some(project.id), title, details)?));
    }
    if todo_path(project)?.is_none() {
        create_todo_file(project)?;
    }
    let head = if kind == CaptureKind::Todo { title.to_string() } else { format!("{}: {title}", kind.label()) };
    let (id, _) = edit_todo(project, |doc| {
        // Plain-line files have no sections and no continuation lines: the details join the line.
        let (section, text) = match (doc.style.marker, details.is_empty()) {
            (_, true) => (if doc.style.marker == Marker::Line { "" } else { INBOX }, head),
            (Marker::Line, false) => ("", format!("{head} — {}", details.split_whitespace().collect::<Vec<_>>().join(" "))),
            (_, false) => (INBOX, format!("{head}\n{details}")),
        };
        Ok(doc.add_on_top(section, &text)?)
    })?;
    Ok(Captured::Todo { file: todo_path(project)?.unwrap_or_default(), id })
}

