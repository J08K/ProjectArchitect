/// Group and purpose names by id, for summaries.
pub struct Catalog {
    pub groups: Vec<Group>,
    pub purposes: Vec<Purpose>,
}

impl Catalog {
    pub fn load(store: &Store) -> Result<Catalog> {
        Ok(Catalog { groups: store.groups()?, purposes: store.purposes()? })
    }

    pub fn group_name(&self, id: Option<i64>) -> Option<&str> {
        let id = id?;
        self.groups.iter().find(|g| g.id == id).map(|g| g.name.as_str())
    }

    pub fn purpose(&self, id: Option<i64>) -> Option<&Purpose> {
        let id = id?;
        self.purposes.iter().find(|p| p.id == id)
    }
}
