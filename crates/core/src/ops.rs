/// Changes to a project's own fields. `None` leaves a field alone; `Some(None)` clears a link.
#[derive(Default)]
pub struct ProjectEdit {
    pub name: Option<String>,
    pub group_id: Option<Option<i64>>,
    pub purpose_id: Option<Option<i64>>,
    pub status: Option<Status>,
    pub tags: Option<Vec<String>>,
    /// Encoded TODO style (`Style::encode`); `Some(None)` = detect it again.
    pub todo_style: Option<Option<String>>,
    /// Release tag prefix; `Some(None)` = the default `v`, `Some(Some(""))` = bare versions.
    pub tag_prefix: Option<Option<String>>,
}

/// Apply `e` to `p` and save it.
pub fn edit_project(store: &Store, p: &mut Project, e: ProjectEdit) -> Result<()> {
    if let Some(name) = e.name {
        let name = name.trim();
        if name.is_empty() {
            return fail("a project needs a name");
        }
        p.name = name.to_string();
    }
    if let Some(g) = e.group_id {
        p.group_id = g;
    }
    if let Some(v) = e.purpose_id {
        p.purpose_id = v;
    }
    if let Some(s) = e.status {
        p.status = s;
    }
    if let Some(t) = e.tags {
        p.tags = t.into_iter().map(|t| t.trim().to_string()).filter(|t| !t.is_empty()).collect();
    }
    if let Some(s) = e.todo_style {
        p.todo_style = s;
    }
    if let Some(t) = e.tag_prefix {
        p.tag_prefix = t;
    }
    store.update_project(p)?;
    Ok(())
}

// --- release tags -----------------------------------------------------------------------------------------------

/// The project's tag names (`git tag --list` in the primary checkout). Empty without git or a checkout.
pub fn tags(project: &Project) -> Vec<String> {
    primary_root(project).ok().and_then(|root| git::tags(&root).ok()).unwrap_or_default()
}

/// The prefix of the project's release tags: its own setting, else `v`. `""` means bare versions (`1.2.3`).
pub fn tag_prefix(project: &Project) -> &str {
    project.tag_prefix.as_deref().unwrap_or("v")
}

// --- import ---------------------------------------------------------------------------------------------------

/// Where [`import_folder`] put the folder.
pub struct Imported {
    pub project_id: i64,
    /// False when the folder became a checkout of an existing project.
    pub created: bool,
}

/// Track a folder (SPEC § 4). A folder of a repository that a tracked project already has (same root commit or same
/// GitHub remote, D-12) becomes a checkout of that project; anything else is a new project. Without a group, the
/// group whose folder is the parent is used, as the Import view does.
pub fn import_folder(store: &Store, path: &Path, name: Option<&str>, group: Option<&str>, purpose: Option<&str>) -> Result<Imported> {
    if !path.is_dir() {
        return fail(format!("{} is not a folder", path.display()));
    }
    let root = crate::norm(path);
    let projects = store.projects()?;
    if let Some(p) = projects.iter().find(|p| p.checkouts.iter().any(|c| c.path.eq_ignore_ascii_case(&root))) {
        return fail(format!("{root} is already a checkout of {} (#{})", p.name, p.id));
    }
    let group_id = match group {
        Some(g) => Some(group_named(store, g)?),
        None => parent_group(store, &root)?,
    };
    let purpose_id = purpose.map(|p| purpose_named(store, p)).transpose()?;
    if let Some(id) = same_repo_project(&projects, &root) {
        store.add_checkout(id, &root)?;
        return Ok(Imported { project_id: id, created: false });
    }
    let name = name.map_or_else(|| crate::folder_name(&root), str::to_string);
    let project_id = store.add_project(&name, group_id, purpose_id, std::slice::from_ref(&root))?;
    Ok(Imported { project_id, created: true })
}

fn parent_group(store: &Store, root: &str) -> Result<Option<i64>> {
    let parent = Path::new(root).parent().map(crate::norm);
    Ok(store.groups()?.into_iter().find(|g| g.path.is_some() && g.path == parent).map(|g| g.id))
}

fn same_repo_project(projects: &[Project], root: &str) -> Option<i64> {
    let mine = repo_identity(root);
    if mine == (None, None) {
        return None;
    }
    projects.iter().find(|p| p.checkouts.iter().any(|c| same_identity(&repo_identity(&c.path), &mine))).map(|p| p.id)
}

/// `(origin remote, root commit)` of a git checkout; `(None, None)` for a plain folder, even one inside a repository.
fn repo_identity(path: &str) -> (Option<String>, Option<String>) {
    if Path::new(path).join(".git").exists() { info::identity(Path::new(path)) } else { (None, None) }
}

/// Same repository (D-12): equal root commit, or equal `origin` (https/ssh spellings compare equal). Used by the
/// GUI's Import view and `import_folder`.
pub fn same_identity(a: &(Option<String>, Option<String>), b: &(Option<String>, Option<String>)) -> bool {
    let root = matches!((&a.1, &b.1), (Some(x), Some(y)) if x == y);
    let remote = matches!((&a.0, &b.0), (Some(x), Some(y)) if remote_key(x) == remote_key(y));
    root || remote
}

/// Remote without scheme, `.git` or case, so https and ssh remotes of one repository compare equal.
fn remote_key(remote: &str) -> String {
    info::github_url(remote).unwrap_or_else(|| remote.trim().trim_end_matches('/').trim_end_matches(".git").to_string()).to_lowercase()
}

/// Suggestions from the scan roots (or `roots`, at depth 3 each). Nothing is tracked.
pub fn scan_folders(store: &Store, roots: Option<Vec<(String, u32)>>) -> Result<scan::ScanResult> {
    let roots = match roots {
        Some(r) => r,
        None => store.scan_roots()?,
    };
    let tracked: HashSet<String> = store.projects()?.into_iter().flat_map(|p| p.checkouts).map(|c| c.path).collect();
    Ok(scan::scan(&roots, &store.ignored()?, &tracked))
}

// --- TODO files -----------------------------------------------------------------------------------------------

/// The project's TODO file: its own setting, else the first known name. `None` when it has none.
pub fn todo_path(project: &Project) -> Result<Option<PathBuf>> {
    Ok(todo_path_in(project, &primary_root(project)?))
}

/// The TODO file in a given checkout (the GUI works on the selected one): the project's own path, else found.
pub fn todo_path_in(project: &Project, root: &Path) -> Option<PathBuf> {
    match &project.todo_path {
        Some(rel) => Some(root.join(rel)),
        None => todo::find_file(root),
    }
}

/// The style a TODO text is read and written with: the stored style, else detected from the text.
pub fn style_of(project: &Project, text: &str) -> Style {
    project.todo_style.as_deref().and_then(Style::decode).unwrap_or_else(|| Style::detect(text))
}

/// A TODO file as read.
pub struct TodoFile {
    pub path: PathBuf,
    pub text: String,
    pub doc: TodoDoc,
}

pub fn load_todo(project: &Project) -> Result<TodoFile> {
    let Some(path) = todo_path(project)? else {
        return fail(format!("{} has no TODO file; create_todo_file makes one", project.name));
    };
    let text = std::fs::read_to_string(&path).map_err(|e| Error(format!("{}: {e}", path.display())))?;
    let doc = todo::parse_with(&text, &style_of(project, &text));
    Ok(TodoFile { path, text, doc })
}

/// Apply `edit` to the TODO file and save it: lossless and atomic, refused when the file changed since it was read.
/// Returns what `edit` returned and the saved document.
pub fn edit_todo<T>(project: &Project, edit: impl FnOnce(&mut TodoDoc) -> Result<T>) -> Result<(T, TodoDoc)> {
    let mut file = load_todo(project)?;
    let out = edit(&mut file.doc)?;
    todo::save(&file.path, &file.text, &file.doc.render())?;
    Ok((out, file.doc))
}

/// Create `TODO.md` in the app format in the primary checkout. Refused when the project has a TODO file.
pub fn create_todo_file(project: &Project) -> Result<PathBuf> {
    if let Some(p) = todo_path(project)? {
        return fail(format!("{} already has a TODO file: {}", project.name, p.display()));
    }
    let path = primary_root(project)?.join("TODO.md");
    todo::save(&path, "", "# TODO\n\n## Open\n")?;
    Ok(path)
}

// --- TODO style -----------------------------------------------------------------------------------------------

/// Where a TODO style change goes (D-23).
pub enum StyleTarget {
    /// Rewrite the file in the working copy; a backup is taken first.
    WorkingCopy,
    /// Commit to `name` (created from `base`) without touching the working tree; optionally push and open a PR.
    Branch { name: String, base: Option<String>, push_and_pr: bool },
}

/// What [`change_todo_style`] did.
pub struct StyleChange {
    pub file: PathBuf,
    /// The style as stored (`Style::encode`).
    pub style: String,
    pub backup: Option<PathBuf>,
    pub branch: Option<String>,
    pub commit: Option<String>,
    pub pr_url: Option<String>,
}

/// Whether the MCP server may push and open pull requests (the `mcp.allow_publish` setting).
pub fn publish_allowed(store: &Store) -> Result<bool> {
    Ok(store.setting(ALLOW_PUBLISH)?.as_deref() == Some("true"))
}

/// Rewrite the project's TODO file in `style`. The stored style follows when the change lands in the checked-out
/// branch (the working copy).
pub fn change_todo_style(store: &Store, data_dir: &Path, project: &mut Project, style: &Style, target: StyleTarget) -> Result<StyleChange> {
    if matches!(target, StyleTarget::Branch { push_and_pr: true, .. }) && !publish_allowed(store)? {
        return fail(format!(
            "publishing is off: set the app setting {ALLOW_PUBLISH} to true (Settings in ProjectArchitect) to allow push and pull requests"
        ));
    }
    let file = load_todo(project)?;
    let after = todo::convert_to(&file.text, style);
    let root = primary_root(project)?;
    let message = format!("Change TODO style to: {}", style.label());
    let mut change = StyleChange { file: file.path.clone(), style: style.encode(), backup: None, branch: None, commit: None, pr_url: None };
    match target {
        StyleTarget::WorkingCopy => {
            change.backup = Some(todo::backup(data_dir, &file.path)?);
            todo::save(&file.path, &file.text, &after)?;
            project.todo_style = Some(style.encode());
            store.update_project(project)?;
        }
        StyleTarget::Branch { name, base, push_and_pr } => {
            let rel = file.path.strip_prefix(&root).unwrap_or(&file.path).to_string_lossy().replace('\\', "/");
            let base = base.or_else(|| git::default_branch(&root)).or_else(|| git::current_branch(&root)).unwrap_or_else(|| "main".into());
            let on_current = git::current_branch(&root).as_deref() == Some(name.as_str());
            if on_current && std::fs::read_to_string(&file.path)? != file.text {
                return fail(format!("{} changed since it was read; read it again", file.path.display()));
            }
            change.commit = Some(git::commit_file_to_branch(&root, &rel, &after, &name, &base, &message)?);
            if push_and_pr {
                git::push(&root, &name)?;
                change.pr_url = Some(git::open_pr(&root, &name, &base, &message, PR_BODY)?);
            }
            if on_current {
                project.todo_style = Some(style.encode());
                store.update_project(project)?;
            }
            change.branch = Some(name);
        }
    }
    Ok(change)
}

