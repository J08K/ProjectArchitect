// --- notes ----------------------------------------------------------------------------------------------------

/// A note by id, over the global notes and every project's notes.
// ponytail: scans every note; a store lookup by id if the list grows.
pub fn find_note(store: &Store, id: i64) -> Result<Note> {
    let mut all = store.notes(None)?;
    for p in store.projects()? {
        all.extend(store.notes(Some(p.id))?);
    }
    match all.into_iter().find(|n| n.id == id) {
        Some(n) => Ok(n),
        None => fail(format!("no note with id {id}")),
    }
}

/// Create (no `id`) or update a note. Updating keeps the note's project.
pub fn write_note(store: &Store, id: Option<i64>, project_id: Option<i64>, title: &str, body: &str) -> Result<Note> {
    let id = match id {
        Some(id) => id,
        None => store.add_note(project_id, title)?,
    };
    let mut n = find_note(store, id)?;
    n.title = title.to_string();
    n.body = body.to_string();
    store.update_note(&n)?;
    find_note(store, id)
}

/// Delete a note by id.
pub fn delete_note(store: &Store, id: i64) -> Result<()> {
    find_note(store, id)?;
    store.delete_note(id)?;
    Ok(())
}

