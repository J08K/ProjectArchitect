/// A roadmap file as read.
pub struct RoadmapFile {
    pub path: PathBuf,
    pub text: String,
    pub roadmap: Roadmap,
}

pub fn load_roadmap(project: &Project) -> Result<RoadmapFile> {
    let Some(path) = roadmap_path(project)? else {
        return fail(format!("{} has no ROADMAP.md", project.name));
    };
    let text = std::fs::read_to_string(&path).map_err(|e| Error(format!("{}: {e}", path.display())))?;
    let roadmap = roadmap::parse_roadmap(&text);
    Ok(RoadmapFile { path, text, roadmap })
}

/// Apply `edit` to the roadmap and save it, with the same guarantees as [`edit_todo`]. Table roadmaps are refused.
pub fn edit_roadmap<T>(project: &Project, edit: impl FnOnce(&mut Roadmap) -> Result<T>) -> Result<(T, Roadmap)> {
    let mut file = load_roadmap(project)?;
    if !file.roadmap.editable {
        return fail("the roadmap is a table the app cannot edit; convert it to milestones in the app first");
    }
    let out = edit(&mut file.roadmap)?;
    file.roadmap.reparse();
    todo::save(&file.path, &file.text, &file.roadmap.render())?;
    Ok((out, file.roadmap))
}

