/// A failed operation. The message is for the person or the agent.
#[derive(Debug)]
pub struct Error(pub String);

pub type Result<T> = std::result::Result<T, Error>;

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

macro_rules! from_err {
    ($($t:ty),*) => {
        $(impl From<$t> for Error {
            fn from(e: $t) -> Self {
                Error(e.to_string())
            }
        })*
    };
}
from_err!(rusqlite::Error, io::Error, TodoError, SaveError, GitError);

fn fail<T>(msg: impl Into<String>) -> Result<T> {
    Err(Error(msg.into()))
}

// --- finding projects -----------------------------------------------------------------------------------------

/// A project by id, by name (case-insensitive) or by a path inside one of its checkouts, in that order.
pub fn find_project(store: &Store, key: &str) -> Result<Project> {
    let key = key.trim();
    let projects = store.projects()?;
    if let Ok(id) = key.parse::<i64>()
        && let Some(p) = projects.iter().find(|p| p.id == id)
    {
        return Ok(p.clone());
    }
    let named: Vec<&Project> = projects.iter().filter(|p| p.name.eq_ignore_ascii_case(key)).collect();
    match named.as_slice() {
        [p] => Ok((*p).clone()),
        [_, _, ..] => fail(format!("several projects are named {key:?}; use the id")),
        [] => match project_for_path(&projects, Path::new(key)) {
            Some(p) => Ok(p.clone()),
            None => fail(format!("no project matches {key:?}: use an id, a name or a path inside a checkout")),
        },
    }
}

/// The project whose checkout contains `path`: longest match, case-insensitive, whole path segments.
pub fn project_for_path<'a>(projects: &'a [Project], path: &Path) -> Option<&'a Project> {
    // Canonical through the nearest folder that exists, so a path not created yet still matches (and a Windows 8.3
    // short name such as RUNNER~1 above it is expanded like the stored checkout paths).
    let (mut base, mut missing) = (path, Vec::new());
    while !base.exists() {
        let (Some(parent), Some(name)) = (base.parent(), base.file_name()) else { break };
        missing.push(name);
        base = parent;
    }
    let mut target = PathBuf::from(crate::norm(base));
    target.extend(missing.iter().rev());
    let target = target.display().to_string().to_lowercase();
    projects
        .iter()
        .flat_map(|p| p.checkouts.iter().map(move |c| (c.path.to_lowercase(), p)))
        .filter(|(root, _)| inside(&target, root))
        .max_by_key(|(root, _)| root.len())
        .map(|(_, p)| p)
}

fn inside(path: &str, root: &str) -> bool {
    let root = root.trim_end_matches(['\\', '/']);
    path == root || path.strip_prefix(root).is_some_and(|rest| rest.starts_with(['\\', '/']))
}

/// The folder of the project's primary checkout.
pub fn primary_root(project: &Project) -> Result<PathBuf> {
    match project.primary() {
        Some(c) => Ok(PathBuf::from(&c.path)),
        None => fail(format!("{} has no checkout", project.name)),
    }
}

/// A group by name (case-insensitive).
pub fn group_named(store: &Store, name: &str) -> Result<i64> {
    match store.groups()?.into_iter().find(|g| g.name.eq_ignore_ascii_case(name)) {
        Some(g) => Ok(g.id),
        None => fail(format!("no group named {name:?}")),
    }
}

/// A purpose by name (case-insensitive).
pub fn purpose_named(store: &Store, name: &str) -> Result<i64> {
    match store.purposes()?.into_iter().find(|p| p.name.eq_ignore_ascii_case(name)) {
        Some(p) => Ok(p.id),
        None => fail(format!("no purpose named {name:?}")),
    }
}

